import time
import csv
import numpy as np
import matplotlib.pyplot as plt
import gpsd

def collect_gps_dgps(duration_s=180, host='localhost', port=2947, poll_interval=0.2):
    """
    gpsd???? DGPS ?????? ?????? ???????? duration_s ???? ????.
    (latitude, longitude) ???? ?????? ????.
    """
    try:
        gpsd.connect(host=host, port=port)
        print(f"Connected to gpsd at {host}:{port}")
    except Exception as e:
        print(f"gpsd ???? ????: {e}")
        return []

    coords = []
    t0 = time.time()
    while time.time() - t0 < duration_s:
        try:
            report = gpsd.get_current()
            lat = getattr(report, 'lat', None)
            lon = getattr(report, 'lon', None)
            if lat and lon and lat != 0 and lon != 0:
                coords.append((lat, lon))
        except Exception:
            continue
        time.sleep(poll_interval)

    return coords


def compute_density_latlon(coords, bins=50):
    """
    ?????? (lat, lon) ???????? 2D ?????????????? ????.
    H: counts matrix, lon_edges, lat_edges ????.
    """
    lats = np.array([lat for lat, lon in coords])
    lons = np.array([lon for lat, lon in coords])
    H, lon_edges, lat_edges = np.histogram2d(lons, lats, bins=bins)
    return H, lon_edges, lat_edges


def find_peak_latlon(H, lon_edges, lat_edges):
    """
    ?????????? H???? ???? ???? ?? ???? ?????? ????.
    """
    idx = np.unravel_index(np.argmax(H), H.shape)
    i_lon, i_lat = idx
    lon_center = (lon_edges[i_lon] + lon_edges[i_lon+1]) / 2
    lat_center = (lat_edges[i_lat] + lat_edges[i_lat+1]) / 2
    return lat_center, lon_center


def plot_density_latlon(coords, H, lon_edges, lat_edges,
                        peak_latlon, output_file='gps_density_latlon.png'):
    """
    ?????? ?????? ???????? ???? ???? ????.
    """
    lats = np.array([lat for lat, lon in coords])
    lons = np.array([lon for lat, lon in coords])
    peak_lat, peak_lon = peak_latlon

    fig, ax = plt.subplots(figsize=(8,6))
    extent = [lon_edges[0], lon_edges[-1], lat_edges[0], lat_edges[-1]]
    ax.imshow(H.T, origin='lower', extent=extent, aspect='auto', alpha=0.6)
    ax.scatter(lons, lats, s=5, c='white', alpha=0.5)
    ax.plot(peak_lon, peak_lat, 'ro', markersize=12, label='Peak Density')
    ax.set_title('GPS Position Density (Lat/Lon)')
    ax.set_xlabel('Longitude')
    ax.set_ylabel('Latitude')
    ax.legend(loc='upper right')

    coord_str = f"Representative coordinate: {peak_lat:.6f}, {peak_lon:.6f}"
    fig.text(0.5, 0.02, coord_str, ha='center', fontsize=10)

    plt.tight_layout(rect=[0, 0.05, 1, 1])
    plt.savefig(output_file, dpi=300)
    plt.close()


